#!/usr/bin/env python3
"""Regenerate shared/src/oui-table.ts from a local IEEE-derived oui.txt (e.g. /usr/share/hwdata/oui.txt). Offline only.

Usage: python3 -B tools/gen-oui.py <oui.txt> > shared/src/oui-table.ts

The snapshot is identified by the input's sha256 and mtime (UTC date), never by a free-text label.

Only organisations matched by an anchored RULES pattern are kept, under a short brand name; everything else is left out on purpose
(the table is incomplete and a missing prefix means "unknown maker", never a guess). The first matching rule wins per prefix.
"""
import hashlib
import os
import re
import sys
import time

# (brand shown to parents, anchored case-sensitive pattern on the IEEE organisation name)
RULES = [
    ('Apple', r'^Apple, Inc\.?$|^Apple Inc'),
    ('Samsung', r'^Samsung Electronics'),
    ('Google', r'^Google, Inc|^Google LLC'),
    ('Amazon', r'^Amazon Technologies'),
    ('Sonos', r'^Sonos, Inc|^Sonos Inc'),
    ('Roku', r'^Roku, Inc'),
    ('Nintendo', r'^Nintendo'),
    ('Sony', r'^Sony (Corporation|Interactive|Mobile|Home|Video|Computer|Imaging)'),
    ('Microsoft', r'^Microsoft( Corporation| Corp\.| Mobile Oy)?$'),
    ('Xiaomi', r'^Xiaomi'),
    ('Huawei', r'^Huawei (Device|Technologies)'),
    ('Raspberry Pi', r'^Raspberry Pi'),
    ('TP-Link', r'^TP-LINK|^TP-Link'),
    ('Netgear', r'^NETGEAR$'),
    ('GL.iNet', r'^GL Technologies \(Hong Kong\)'),
    ('Intel', r'^Intel Corporate'),
    ('Realtek', r'^REALTEK SEMICONDUCTOR'),
    ('Espressif', r'^Espressif'),
    ('Ubiquiti', r'^Ubiquiti'),
    ('Proxmox', r'^Proxmox'),
    ('Synology', r'^Synology'),
    ('QNAP', r'^QNAP'),
    ('LG', r'^LG Electronics'),
    ('Nest', r'^Nest Labs'),
    ('Ring', r'^Ring LLC'),
    ('Signify (Philips Hue)', r'^Signify|^Philips Lighting'),
    ('OnePlus', r'^OnePlus'),
    ('Valve', r'^Valve Corporation'),
    ('Meta', r'^Meta Platforms|^Facebook'),
    ('NVIDIA', r'^NVIDIA|^Nvidia'),
    ('Tuya', r'^Tuya'),
    ('Wyze', r'^Wyze'),
    ('Arlo', r'^Arlo'),
    ('ecobee', r'^ecobee'),
    ('Belkin', r'^Belkin'),
    ('Brother', r'^Brother Industries'),
    ('Canon', r'^Canon Inc'),
    ('Epson', r'^Seiko Epson'),
    ('HP', r'^HP Inc|^Hewlett Packard$'),
    ('Dell', r'^Dell Inc|^Dell Technologies'),
    ('Lenovo', r'^Lenovo'),
    ('ASUS', r'^ASUSTek'),
    ('D-Link', r'^D-Link'),
    ('Motorola', r'^Motorola'),
    ('Vizio', r'^Vizio|^VIZIO'),
    ('TCL', r'^TCL'),
    ('Hisense', r'^Hisense'),
    ('Bose', r'^Bose'),
]

def snapshot(path):
    with open(path, 'rb') as handle:
        digest = hashlib.sha256(handle.read()).hexdigest()
    return f"sha256 {digest}, mtime {time.strftime('%Y-%m-%d', time.gmtime(os.stat(path).st_mtime))} UTC"

def main(path):
    label = snapshot(path)
    compiled = [(brand, re.compile(p)) for brand, p in RULES]
    found = {}
    with open(path, encoding='utf-8', errors='replace') as handle:
        for line in handle:
            m = re.match(r'^([0-9A-F]{6})\s+\(base 16\)\s+(.+?)\s*$', line)
            if not m:
                continue
            prefix, org = m.group(1).lower(), m.group(2)
            for brand, pattern in compiled:
                if pattern.search(org):
                    found.setdefault(prefix, brand)
                    break
    by_brand = {}
    for prefix, brand in sorted(found.items()):
        by_brand.setdefault(brand, []).append(prefix)
    out = ['// GENERATED by tools/gen-oui.py - do not edit by hand. See shared/src/oui.ts and docs/oui-table.md for provenance.',
           f'// Source snapshot: oui.txt {label} (IEEE MA-L registry, as shipped in hwdata). Prefixes kept: {len(found)}. INCOMPLETE by design.',
           'export const OUI_VENDORS: readonly (readonly [vendor: string, prefixes: readonly string[]])[] = [']
    for brand, _ in RULES:
        prefixes = by_brand.get(brand)
        if not prefixes:
            continue
        out.append(f"    [{brand!r}, [".replace('"', "'"))
        for i in range(0, len(prefixes), 12):
            out.append("        " + ", ".join(f"'{p}'" for p in prefixes[i:i + 12]) + ",")
        out.append("    ]],")
    out.append('];')
    sys.stdout.write("\n".join(out) + "\n")

if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit('usage: gen-oui.py <oui.txt>')
    main(sys.argv[1])
